// Regenerates src/mock-data/seedRoads.ts — real road geometry (OSRM) for the seeded demo routes,
// so they render on actual roads without a network call. Run: node scripts/gen-seed-roads.ts
// Keep the stop lists in sync with routeSeeds in src/mock-data/seed.ts.
import { writeFileSync } from "node:fs";
import { LOCATIONS } from "../src/mock-data/locations.ts";
import { encodePolyline, fetchRoadRoutes } from "../src/services/routing/roadRouting.ts";

const SEEDS: Record<string, string[]> = {
  R000: ["LOC-HCM", "LOC-LONGTHANH", "LOC-DAUGIAY", "LOC-QUYNHON", "LOC-DANANG"],
  R001: ["LOC-HCM-TB", "LOC-TD-NT", "LOC-CATLAI"],
  "R001:return": ["LOC-CATLAI", "LOC-TD-NT", "LOC-HCM-TB"],
  R002: ["LOC-HCM-Q7", "LOC-SONGTHAN", "LOC-BINHDUONG"],
  R003: ["LOC-HCM-TD", "LOC-BIENHOA2"],
  R004: ["LOC-GIALAM", "LOC-HAIDUONG", "LOC-DINHVU"],
  "R004:return": ["LOC-DINHVU", "LOC-HAIPHONG", "LOC-GIALAM"],
  R006: ["LOC-HCM", "LOC-LONGTHANH"],
  R007: ["LOC-DANANG", "LOC-TAMKY", "LOC-QUYNHON"],
};

const out: Record<string, [number, string][]> = {};
for (const [key, ids] of Object.entries(SEEDS)) {
  const pts = ids.map((id) => {
    const l = LOCATIONS.find((x) => x.id === id);
    if (!l) throw new Error(`Unknown location ${id}`);
    return { lat: l.lat, lng: l.lng };
  });
  const roads = await fetchRoadRoutes(pts, key.endsWith(":return") ? 1 : 3);
  out[key] = roads.map((r) => [r.distanceKm, encodePolyline(r.geometry)]);
  console.log(key, roads.map((r) => `${r.distanceKm} km/${r.geometry.length} pts`).join(", "));
  await new Promise((r) => setTimeout(r, 1200)); // be polite to the public OSRM server
}

writeFileSync(
  "src/mock-data/seedRoads.ts",
  `// Generated by scripts/gen-seed-roads.ts — real road geometry (OSRM, © OpenStreetMap contributors).
// [distanceKm, encoded polyline (precision 5)] per alternative; "<id>:return" = return leg.
export const SEED_ROADS: Record<string, [number, string][]> = ${JSON.stringify(out, null, 2)};
`,
);
